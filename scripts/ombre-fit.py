#!/usr/bin/env python3
"""
The pink ombre backgrounds as CSS gradients (Bohoka 2026-11-04: “replace the picture with the same ombre”).

Each drawn texture in design/ombre/ (exported from Figma) is smoothed (its grain comes back as a CSS noise layer)
and fitted, least squares, by a 6 x 14 grid that CSS draws exactly: one left-to-right linear-gradient per row,
stacked, each row fading in from the one above (src/styles/ombre.css). CSS interpolates gradients and masks in
sRGB, the same space as the fit. Mean colour difference ΔE76 ≈ 0.5 (below what an eye can see).

Run: python3 scripts/ombre-fit.py   (rewrites the generated block in src/styles/tokens.css)
Needs: numpy, Pillow.
"""
import re
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
ROWS, COLS = 6, 14
# The grain: Figma's noise is drawn by CSS on top (src/styles/ombre.css), at an opacity per surface that matches the
# fine detail measured in each picture. A white noise layer lightens on average (alpha 0.1719 at opacity 1, measured
# in Chromium), so the gradient underneath is fitted that much darker.
NOISE_ALPHA = 0.1719
GRAIN = {
    "header": 0.81,
    "menu": 0,  # the menu keeps its own noise layer (mobile-menu.module.css)
    "footer-phone": 0.82,
    "footer-tablet": 0.65,
    "footer-desktop": 0.79,
    "home-band": 0,
    "range-phone": 0.81,
    "range-desktop": 0.33,
}
SOURCES = {
    "header": "header.webp",
    "menu": "menu.webp",
    "footer-phone": "footer-phone.webp",
    "footer-tablet": "footer-tablet.webp",
    "footer-desktop": "footer-desktop.webp",
    "home-band": "home-band.webp",
    "range-phone": "range-phone.webp",
    "range-desktop": "range-desktop.webp",
}


def lab(rgb):
    c = rgb / 255.0
    c = np.where(c > 0.04045, ((c + 0.055) / 1.055) ** 2.4, c / 12.92)
    m = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]])
    xyz = c @ m.T / np.array([0.95047, 1.0, 1.08883])
    f = np.where(xyz > 0.008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]), 200 * (f[..., 1] - f[..., 2])], -1)


def hat(n, k):
    t = np.linspace(0, 1, n)[:, None]
    knots = np.linspace(0, 1, k)[None, :]
    return np.clip(1 - np.abs(t - knots) * (k - 1), 0, 1)


def fit(path, grain):
    im = Image.open(path).convert("RGB")
    a = np.asarray(im)
    if Image.open(path).mode == "RGBA":  # the tablet footer's last row is half transparent (an export slip)
        a = a[:-1]
        im = Image.fromarray(a)
    seen = np.asarray(im.filter(ImageFilter.GaussianBlur(8))).astype(float)
    a_mean = grain * NOISE_ALPHA
    img = (seen - 255 * a_mean) / (1 - a_mean)
    h, w, _ = img.shape
    ay, ax = hat(h, ROWS), hat(w, COLS)
    py, px = np.linalg.pinv(ay), np.linalg.pinv(ax)
    grid = np.clip(np.stack([py @ img[..., c] @ px.T for c in range(3)], -1), 0, 255).round()
    approx = np.stack([ay @ grid[..., c] @ ax.T for c in range(3)], -1)
    approx = approx * (1 - a_mean) + 255 * a_mean
    de = np.linalg.norm(lab(approx) - lab(seen), axis=-1)
    return grid.astype(int), de.mean(), (w, h)


def main():
    lines = [
        "  /* BEGIN ombre (generated by scripts/ombre-fit.py from design/ombre/; do not edit by hand).",
        "     Each surface: rows 0–5 top to bottom, each a left-to-right gradient; the drawn size as --ombre-*-ratio. */",
        "  /* @group Ombre backgrounds */",
    ]
    for name, file in SOURCES.items():
        grid, err, (w, h) = fit(ROOT / "design" / "ombre" / file, GRAIN[name])
        lines.append(
            f"  --ombre-{name}-ratio: {w} / {h}; /* {name} texture's drawn size (mean ΔE {err:.2f}) · design/ombre/{file} */"
        )
        lines.append(
            f"  --ombre-{name}-grain: {GRAIN[name]}; /* {name} noise opacity, as grainy as the picture · design/ombre/{file} */"
        )
        for r in range(ROWS):
            stops = ", ".join(
                f"rgb({c[0]} {c[1]} {c[2]}) {round(100 * i / (COLS - 1), 2)}%" for i, c in enumerate(grid[r])
            )
            lines.append(
                f"  --ombre-{name}-{r}: linear-gradient(to right, {stops}); /* {name} row {r + 1} of {ROWS} · design/ombre/{file} */"
            )
    lines.append("  /* END ombre */")
    tokens = ROOT / "src" / "styles" / "tokens.css"
    text = tokens.read_text()
    block = "\n".join(lines)
    if "BEGIN ombre" in text:
        text = re.sub(r"  /\* BEGIN ombre.*?END ombre \*/", lambda _: block, text, flags=re.S)
    else:
        # Inside the first :root block, at its end.
        i = text.index("\n}", text.index(":root"))
        text = text[:i] + "\n\n" + block + text[i:]
    tokens.write_text(text)
    print("written", tokens)


if __name__ == "__main__":
    main()
